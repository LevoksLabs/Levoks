import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
let output = "// Generated by scripts/sync-export-runtimes.mjs; do not edit.\n";
for (const [fileName, functionName, constant] of [
  ["native-widget-runtime", "setupNativeWidgets", "nativeWidgetSource"],
  ["animation-runtime", "mountAnimations", "advancedAnimationSource"],
]) {
  const input = await readFile(
    new URL(`../src/lib/${fileName}.ts`, import.meta.url),
    "utf8",
  );
  const js = ts.transpileModule(input, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
    },
  }).outputText;
  const file = ts.createSourceFile(
    "runtime.js",
    js,
    ts.ScriptTarget.ES2022,
    true,
    ts.ScriptKind.JS,
  );
  const fn = file.statements.find(
    (node) =>
      ts.isFunctionDeclaration(node) && node.name?.text === functionName,
  );
  if (!fn) throw new Error(`${functionName} missing`);
  output += `export const ${constant} = ${JSON.stringify(fn.getText(file).replace(/^export /, ""))};\n`;
}
const target = new URL(
  "../src/lib/codegen/runtime-sources.ts",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "Export runtimes are stale. Run npm run sync:export-runtimes.",
    );
} else if ((await readFile(target, "utf8").catch(() => "")) !== output)
  await writeFile(target, output);
